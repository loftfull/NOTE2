import { test } from 'node:test'
import assert from 'node:assert/strict'
import { regions, stemAll, stemRu } from '../src/stem-ru.js'

/** Формы одного слова должны сойтись к одной основе. */
const FAMILIES = [
  ['хлеб', 'хлеба', 'хлебу', 'хлебом', 'хлебе'],
  ['рецепт', 'рецепты', 'рецепта', 'рецептов', 'рецептам'],
  ['заметка', 'заметки', 'заметкам', 'заметками', 'заметке'],
  ['книга', 'книги', 'книгами', 'книгу', 'книге'],
  ['работа', 'работе', 'работу', 'работой', 'работы'],
  ['источник', 'источника', 'источники', 'источников', 'источнику'],
  ['задача', 'задачи', 'задачам', 'задачу'],
  ['вода', 'воду', 'водой', 'воды'],
  ['приложение', 'приложения', 'приложению', 'приложением']
]

for (const family of FAMILIES) {
  test(`формы «${family[0]}» сходятся к одной основе`, () => {
    const stems = [...new Set(family.map(word => stemRu(word)))]
    assert.equal(stems.length, 1, `${family.join(', ')} → ${stems.join(' / ')}`)
  })
}

test('разные слова не склеиваются в одну основу', () => {
  // Стеммер без словаря иногда объединяет лишнее; эти пары он объединять не
  // должен, иначе поиск начнёт выдавать явно постороннее.
  const distinct = [['хлеб', 'хлев'], ['книга', 'кнопка'], ['вода', 'вожак'], ['работа', 'ребёнок'], ['поиск', 'письмо']]
  for (const [a, b] of distinct) {
    assert.notEqual(stemRu(a), stemRu(b), `${a} и ${b} не должны совпасть`)
  }
})

test('короткие и нерусские слова не трогаются', () => {
  assert.equal(stemRu('дом'), 'дом', 'короче четырёх букв')
  assert.equal(stemRu('PDF'), 'pdf')
  assert.equal(stemRu('gateway'), 'gateway')
  assert.equal(stemRu('note2'), 'note2')
  assert.equal(stemRu(''), '')
})

test('ё приводится к е, регистр снимается', () => {
  assert.equal(stemRu('Ёлка'), stemRu('елка'))
  assert.equal(stemRu('ЗАМЕТКИ'), stemRu('заметки'))
})

test('глагольные формы сходятся', () => {
  assert.equal(stemRu('читал'), stemRu('читать'))
  assert.equal(stemRu('делали'), stemRu('делать'))
})

test('возвратная форма теряет -ся', () => {
  assert.equal(stemRu('учиться'), stemRu('учить'))
})

test('regions находит RV, R1 и R2', () => {
  // По определению алгоритма: RV — после первой гласной, R1 — после первой
  // пары «гласная+согласная», R2 — то же внутри R1.
  // RV — область ПОСЛЕ первой гласной, а не начиная с неё.
  const { rv, r1, r2 } = regions('красота')
  assert.equal('красота'.slice(rv), 'сота')
  assert.equal('красота'.slice(r1), 'ота')
  assert.equal('красота'.slice(r2), 'а')
})

test('stemAll обрабатывает список и выбрасывает пустое', () => {
  assert.deepEqual(stemAll(['Хлеба', 'рецепты', '']), [stemRu('хлеб'), stemRu('рецепт')])
})

test('стемминг детерминирован', () => {
  // Одно и то же слово всегда даёт одну и ту же основу — на этом держится
  // совпадение запроса с индексом.
  for (const word of ['хлеба', 'рецептами', 'заметки', 'источников', 'читал']) {
    assert.equal(stemRu(word), stemRu(word))
    assert.equal(stemRu(word), stemRu(word.toUpperCase()))
  }
})

test('повторный прогон по основе может обрезать дальше — поэтому его не делают', () => {
  // Snowball не идемпотентен и не обязан быть. Свойство зафиксировано, чтобы
  // никто не «исправил» это, начав стеммить уже сохранённые основы.
  assert.equal(stemRu('читал'), 'чита')
  assert.equal(stemRu('чита'), 'чит', 'именно поэтому стеммим только исходные слова')
})
