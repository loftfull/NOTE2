// Что именно просят у модели для каждого действия.
//
// Почему отдельный модуль, общий для клиента и сервера: инструкции были
// только на серверном пути (server/routes/ai.mjs), а прямой путь к провайдеру
// — тот, которым пользуются без своего сервера, — параметр `action` принимал и
// молча игнорировал.
//
// Последствие было видно в прогоне: «Сводка», «Улучшить», «Ключевые слова» и
// «Название» отправляли байт в байт одинаковый запрос. Модель не могла знать,
// чего от неё хотят, и четыре кнопки делали одно и то же. Найдено проверкой
// на реальном прогоне, а не чтением кода.
//
// Инструкции короткие и на русском: они уходят модели, и на них же смотрит
// человек, когда результат не такой, как ожидал.

