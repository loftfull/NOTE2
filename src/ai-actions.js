export const DEFAULT_SYSTEM =
  'Ты помощник в личной базе знаний. Отвечай по существу, на языке пользователя. ' +
  'Не выдумывай факты: если данных не хватает, скажи об этом прямо.'

/**
 * Системная инструкция для запроса.
 *
 * Инструкция действия добавляется к системному тексту вызывающего, а не
 * заменяет его: вызывающий знает про контекст («работай только с этой
 * заметкой»), а действие — про форму ответа. Нужны оба.
 */
export function systemFor(action, callerSystem = '') {
  const instruction = ACTION_PROMPTS[action] || ''
  const parts = [String(callerSystem || '').trim() || DEFAULT_SYSTEM, instruction].filter(Boolean)
  return parts.join('\n\n')
}

/** Действия, для которых инструкция вообще определена. */
export function knownActions() {
  return Object.keys(ACTION_PROMPTS)
}
